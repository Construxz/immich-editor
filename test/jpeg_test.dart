/// Orientation tag from IFD0 of an EXIF payload.
int orientation(Uint8List exif) {
  final d = ByteData.sublistView(exif);
  final e = exif[6] == 0x49 ? Endian.little : Endian.big;
  final ifd0 = 6 + d.getUint32(10, e);
  for (var n = 0; n < d.getUint16(ifd0, e); n++) {
    final entry = ifd0 + 2 + n * 12;
    if (d.getUint16(entry, e) == 0x0112) return d.getUint16(entry + 8, e);
  }
  return -1;
}

